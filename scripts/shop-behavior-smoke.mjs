import assert from 'node:assert/strict';

export async function checkShopBehavior(browser,base,errors){
  const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(()=>{
    if(localStorage.getItem('shop-behavior-seeded'))return;
    localStorage.setItem('shop-behavior-seeded','true');localStorage.setItem('jelly-coins','10000');
    localStorage.setItem('jelly-profile',JSON.stringify({owned:['skins:fuzzies'],selected:{skins:'fuzzies'}}));
    localStorage.setItem('jelly-discovered','2047');
  });
  await page.goto(base,{waitUntil:'networkidle'});await page.locator('.loading').waitFor({state:'detached'});
  const profile=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('jelly-profile')));
  const open=async()=>{await page.getByRole('button',{name:'Магазин',exact:true}).click();await page.waitForTimeout(350);};
  const close=async()=>{await page.getByRole('button',{name:'Закрыть',exact:true}).click();await page.locator('.overlay').waitFor({state:'detached'});};
  const choose=async(name)=>{await page.locator('[data-category=skins]').getByRole('button',{name:`Показать ${name}`,exact:true}).click();await page.waitForTimeout(500);};
  const jump=async(label)=>{await page.getByRole('navigation',{name:'Разделы магазина'}).getByRole('button',{name:label,exact:true}).click();await page.waitForTimeout(1000);};
  assert.equal(await page.locator('.chain-fruit[data-discovered=true]').count(),1,'Old lifetime discoveries do not enter a new round');
  assert.ok(await page.locator('.shop-launch-art').evaluate(el=>getComputedStyle(el).backgroundColor==='rgba(0, 0, 0, 0.4)'&&el.clientWidth===60));
  assert.ok(await page.locator('.game-toolbar').evaluate(el=>!el.closest('.playfield')&&Math.abs(el.getBoundingClientRect().left-document.querySelector('.scoreboard').getBoundingClientRect().left)<1));
  await open();
  assert.equal(await page.locator('.offer-controls > button').count(),0,'Offer navigation contains only dots');
  assert.equal(await page.locator('.auto-equipped').count(),0,'Automatic equipment needs no extra label');
  assert.equal(await page.getByRole('button',{name:'Выбрать',exact:true}).count(),0,'Shop equips without a separate button');
  const keyframes=await page.locator('.shop-dialog').evaluate(el=>el.getAnimations()[0].effect.getKeyframes());
  assert.ok(keyframes[0].transform.includes('844'),'Sheet entrance begins below the viewport');
  await choose('Фруктовая семья');assert.equal((await profile()).selected.skins,'fruit');
  await choose('Суши-пати');
  await page.waitForFunction(()=>document.querySelector('.chain-fruit img').src.includes('/skins/sushi/'));
  assert.equal((await profile()).selected.skins,'fruit','Locked preview does not become a saved purchase');
  await close();assert.equal((await profile()).selected.skins,'fuzzies','Closing on a locked item restores the selection from before opening');
  await page.waitForFunction(()=>document.querySelector('.chain-fruit img').src.includes('/skins/fuzzies/'));
  await open();await choose('Фруктовая семья');await close();assert.equal((await profile()).selected.skins,'fruit','Closing on an owned item keeps the focused selection');
  await open();await choose('Суши-пати');
  await page.locator('[data-category=skins] .contents-button').click();
  await page.getByRole('dialog',{name:'Содержимое: Суши-пати'}).waitFor();
  assert.equal(await page.locator('.contents-grid figure').count(),11);
  await page.screenshot({path:'test-results/skin-contents.png',animations:'disabled'});
  await page.getByRole('button',{name:'Закрыть содержимое'}).click();await page.locator('.contents-overlay').waitFor({state:'detached'});
  await page.locator('[data-category=skins]').getByRole('button',{name:'Купить за 1200',exact:true}).click();
  assert.equal((await profile()).selected.skins,'sushi','Buying equips immediately');
  await jump('Наборы');await page.getByRole('button',{name:'Купить Уютный набор за 1183'}).click();
  assert.deepEqual((await profile()).selected,{skins:'fuzzies',backgrounds:'sunset',boxes:'rose'},'Bundle equips all three contents');
  await page.locator('.bundle-card.cozy .contents-button').click();
  await page.getByRole('dialog',{name:'Содержимое: Уютный набор'}).waitFor();
  assert.equal(await page.locator('.contents-item').count(),3);assert.match(await page.locator('.contents-shakes').textContent(),/3/);
  await page.screenshot({path:'test-results/bundle-contents.png',animations:'disabled'});
  await page.locator('.contents-item.boxes').click();await page.locator('.contents-overlay').waitFor({state:'detached'});
  await page.waitForFunction(()=>document.querySelector('.shop-nav [aria-current=true]').textContent==='Боксы');
  assert.equal(await page.locator('[data-category=boxes] .shop-current').textContent(),'Розовый кварц');
  await jump('Персонажи');await page.locator('.shop-scroll').evaluate(el=>el.scrollTop=0);
  await page.getByRole('button',{name:'Предложение 1',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.offer-controls [aria-label="Предложение 2"]').getAttribute('aria-pressed')==='true',null,{timeout:12000});
  await page.getByRole('button',{name:'Предложение 1',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.offer-controls [aria-label="Предложение 1"]').getAttribute('aria-pressed')==='true');
  await page.mouse.move(350,550);await page.mouse.wheel(0,300);
  const first=await page.locator('.shop-scroll').evaluate(el=>el.scrollTop);await page.waitForTimeout(80);
  const later=await page.locator('.shop-scroll').evaluate(el=>el.scrollTop);
  assert.ok(later>first+10&&later<310,'Vertical wheel input continues with the shared soft spring');
  await close();
  await page.getByRole('button',{name:'Баланс монет'}).click();
  await page.getByRole('button',{name:/150 монет.*За короткое видео/}).click();
  await page.locator('.ad-overlay').waitFor({state:'detached'});
  assert.equal(Number(await page.getByTestId('coins').getAttribute('data-coins')),7767,'Wallet offers the doubled coin reward');
  await close();await page.close();
  console.log('✓ independent game toolbar, owned focus, locked preview rollback, purchase and bundle auto-equipping, contents windows, automatic offers, soft vertical scroll and wallet ad reward');
}
